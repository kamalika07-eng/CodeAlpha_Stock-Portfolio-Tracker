# Stock Portfolio Tracker

# Step 1: Store stock prices
stocks = {
    "AAPL": 180,
    "TSLA": 250,
    "GOOGL": 150,
    "MSFT": 400,
    "AMZN": 190
}

# Step 2: Initialize total investment
total_investment = 0

# Step 3: Ask how many stocks
n = int(input("How many different stocks do you own? "))

# Step 4: Get stock details
for i in range(n):

    stock_name = input("Enter stock symbol: ").upper()

    if stock_name in stocks:

        quantity = int(input("Enter quantity: "))

        if quantity <= 0:
            print("Please enter a positive quantity.")
            continue

        price = stocks[stock_name]

        investment = price * quantity

        total_investment += investment

        print("Stock:", stock_name)
        print("Price:", price)
        print("Quantity:", quantity)
        print("Investment:", investment)

    else:
        print("Stock not available!")

# Step 5: Display final amount
print("-------------------------")
print("TOTAL INVESTMENT:", total_investment)
print("-------------------------")

# Step 6: Save result in a text file
with open("portfolio.txt", "w") as file:
    file.write("STOCK PORTFOLIO TRACKER\n")
    file.write("Total Investment: " + str(total_investment))

print("Portfolio saved successfully!")

